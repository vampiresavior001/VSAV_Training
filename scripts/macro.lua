local function playcontrol(silent)
	-- Asked again while the start is still waiting: that is a stop, as it is
	-- while playing.
	if start_wait ~= nil then
		start_wait = nil
		inputstream = nil
		slot_override = nil
		if not silent then print("Canceled playback before it started.") print() end
		return
	end
	local slot
	if slot_override ~= nil and not playing then
		slot = slot_override
	elseif globals.options.random_playback then
		slot = get_playback_file(true)
		-- Defensive: this is the only arithmetic on the returned table, and a
		-- crash here takes the whole script down mid-match.
		if type(slot) ~= "table" or type(slot.num) ~= "number" then
			slot = get_playback_file()
		else
			-- The Playback Slot's index is the slot's number (v11.7.28).
			globals.options.recording_slot = slot.num
			slot = slot.slot
		end
	else
		slot = get_playback_file()
	end
	if not playing then
		if not parse(slot) or warning("Macro is zero frames long.", macrosize == 0) or dumpinputstream(dumpmode) then
			slot_override = nil
			return
		end
		local _w = rsw_roll()
		if not silent then
			print("Now playing " .. slot .. " (" .. macrosize .. " frames)" .. (loopmode and " in loop mode" or wait.duration and " in incremental wait mode" or "")
				.. (_w > 0 and (" after a Random Start Wait of " .. _w .. " Ticks") or ""))
		end
		if _w > 0 then
			start_wait = { left = _w, last = memory.readbyte(0xFF8081) }
			return
		end
		dostate(frame)
		playing = true
		playback_serial = playback_serial + 1
		framediff = emu.framecount()
	else
		playing = false
		inputstream = nil
		slot_override = nil
		if wait.duration then
			print("Stopped at wait duration = " .. wait.duration) print()
			wait = {}
		elseif loopmode then
			print("Stopped looping playback on frame " .. frame) print()
		else
			print("Canceled playback on frame " .. frame) print()
		end
	end
end

