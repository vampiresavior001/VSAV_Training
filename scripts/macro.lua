-- Which side the dummy stood on when a recording was made. Playback carries
-- absolute stick directions, so it only reproduces the same move from that
-- same side; finalize writes the value into the .mis header and playback
-- compares against it. The byte is 0 while P2 is on the right and non-zero
-- once the two have swapped (guardCancel's p2_facing_toward_p1).
local P2_FACING_ADDR = 0xFF880B
local rec_facing_at_start = nil  -- sampled when recording begins

-- Where the two stood when the recording began. Written into the header next
-- to the facing, and put back before each pass so a looped playback keeps
-- meeting the dummy at the distance the take was made at instead of drifting
-- apart. X is 16.16: integer half at $10, fraction at $12.
local P1_X_ADDR, P2_X_ADDR = 0xFF8410, 0xFF8810
local rec_pos_at_start = nil     -- {p1 int, p1 frac, p2 int, p2 frac}
local playback_pos = nil         -- the same, from the header being played

local function sample_positions()
	return {
		memory.readword(P1_X_ADDR),     memory.readword(P1_X_ADDR + 2),
		memory.readword(P2_X_ADDR),     memory.readword(P2_X_ADDR + 2),
	}
end

function get_playback_pos()
	return playback_pos
end

function restore_playback_pos()
	if playback_pos == nil then return false end
	-- Handed to position.lua, which moves the camera and the pair together at
	-- 16 pixels a frame - one tile, which is all the background can be drawn
	-- in one - so the framing arrives with them rather than crawling after
	-- them, and no character is left outside the window on the way. The
	-- recordings carry no camera value, so the destination is worked out from
	-- the restored spacing, which is where the camera would settle anyway.
	local pm = positionModule
	if pm ~= nil and pm.camera_restore_start ~= nil then
		pm.camera_restore_start(pm.camera_for(playback_pos[1], playback_pos[3]),
			playback_pos[1], playback_pos[2], playback_pos[3], playback_pos[4])
		return true
	end
	memory.writeword(P1_X_ADDR,     playback_pos[1])
	memory.writeword(P1_X_ADDR + 2, playback_pos[2])
	memory.writeword(P2_X_ADDR,     playback_pos[3])
	memory.writeword(P2_X_ADDR + 2, playback_pos[4])
	return true
end

