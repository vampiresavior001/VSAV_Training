-- RECORDING WIZARD API (Stage A). Minimal exposure over the local recording
-- machinery: begin/stop a temporary recording whose output goes to a fixed
-- temp file instead of the configured slot. The trailing-neutral trim runs
-- here at the source - recframe is pulled back to the last frame that
-- carries any input for any player, so finalize never writes the 120-frame
-- neutral tail the wizard's auto-stop produces. Leading neutrals cannot
-- exist: the wizard only begins the recording ON the first input.
local WIZARD_TEMP_NAME = "wizard_temp.mis"

function begin_temporary_recording()
	if recording then return false end
	recording = true
	recframe = 0
	recinputstream = {}
	rec_facing_at_start = memory.readbyte(P2_FACING_ADDR)
	rec_pos_at_start = sample_positions()
	return true
end

function stop_temporary_recording()
	if not recording then return false end
	local last = 0
	for f = 1, recframe do
		local fr = recinputstream[f]
		if fr ~= nil then
			-- A per-frame entry is a STRING of key symbols (built in
			-- registerAfter), not a table - next() would raise here.
			for p = 1, nplayers do
				if fr[p] ~= nil and fr[p] ~= "" then last = f break end
			end
		end
	end
	recording = false
	if last == 0 then
		recframe = 0
		recinputstream = {}
		print("Wizard recording was empty - discarded.")
		return false
	end
	recframe = last
	finalize(recinputstream, WIZARD_TEMP_NAME)
	return true
end

-- Drop an in-flight wizard recording without writing anything. stop_ is the
-- completion path and always finalizes; a cancel must leave no file behind.
function cancel_temporary_recording()
	if not recording then return false end
	recording = false
	recframe = 0
	recinputstream = {}
	print("Wizard recording cancelled - discarded.") print()
	return true
end

-- QUICK RECORDING (quickRecording.lua, v11.7.28; handoff RECORDING_STATE_DESIGN,
-- sections 2 to 4). A take of its own, begun and ended with Coin, written to
-- the dummy character's quick_recording.mis - never a numbered slot - and
-- played back from there.
--   * Start, Coin, Diagnostic and Reset are not part of a take: the Coin that
--     begins and ends it would otherwise be in it, and played back.
--   * Auto Trim cuts the frames before the first input and after the last
--     (a direction or a button, either player). The facing and positions
--     written into the header are the ones on the frame the first input came
--     on, before it, so Reset Distance Each Loop puts the pair back where the
--     take really began, not where Coin was pressed. Inputs in the middle,
--     and holds, are kept.
--   * Nothing played: the file is left as it was.
local QUICK_NAME = "quick_recording.mis"
local NON_PLAY = "[SC@~]"            -- Start, Coin, Diagnostic, Reset
local quick_rec = nil                -- the take in progress: { trim, first, pos, facing, prev_pos, prev_facing }
local last_user_play = nil           -- "quick" / "slot": what the player started last (replay_last)
local user_owned = false             -- what plays now was started by the player (user_playback)

-- MESSAGES THAT STAY (user, 2026-10-21). While a macro plays or records,
-- registerAfter writes its progress to the emulator's message line every
-- frame, so a message said once (a state saved or refused, a quick take
-- saved) was overwritten the frame after. hold_message says it and keeps the
-- progress off the line for MESSAGE_HOLD frames - about two seconds on screen,
-- a display time and nothing in the game. Counted down here, not from
-- emu.framecount(), which a state load may move.
--
-- The emulator's line did not show at all in play (user, 2026-10-21), so the
-- text is kept for those frames too: Display > Recording GUI draws it under
-- its box (hud.lua draw_rec) - only there, "慣れたらメッセージは不要なはず".
local MESSAGE_HOLD = 120
local message_hold = 0
local held_text = nil
function hold_message(text)
	if emu ~= nil and emu.message ~= nil then emu.message(text) end
	message_hold = MESSAGE_HOLD
	held_text = text
end
function held_message()
	if message_hold > 0 then return held_text end
	return nil
end

function quick_file()
	local dir = (globals ~= nil and globals.dummy ~= nil and globals.dummy.p2_char) or ""
	return dir .. "/" .. QUICK_NAME
end

function begin_quick_recording(trim)
	if recording then return false end
	recording = true
	recframe = 0
	recinputstream = {}
	rec_facing_at_start = memory.readbyte(P2_FACING_ADDR)
	rec_pos_at_start = sample_positions()
	quick_rec = { trim = trim == true, prev_pos = rec_pos_at_start, prev_facing = rec_facing_at_start }
	return true
end

-- One recorded frame of the quick take (registerAfter, right after it is
-- stored): what is not play goes, and the first input's place is kept.
local function quick_frame()
	local q = quick_rec
	if q == nil then return end
	local fr = recinputstream[recframe]
	local any = false
	if fr ~= nil then
		for p = 1, nplayers do
			if fr[p] ~= nil then
				fr[p] = fr[p]:gsub(NON_PLAY, "")
				if fr[p] == "" then fr[p] = nil else any = true end
			end
		end
		if not any then recinputstream[recframe] = nil end
	end
	if any and q.first == nil then
		q.first, q.pos, q.facing = recframe, q.prev_pos, q.prev_facing
	end
	q.prev_pos = sample_positions()
	q.prev_facing = memory.readbyte(P2_FACING_ADDR)
end

-- Ends the take. true and the frames written; false and "empty" when nothing
-- was played (the old file stays).
function finish_quick_recording()
	if not recording or quick_rec == nil then return false, "not recording" end
	local q = quick_rec
	quick_rec = nil
	recording = false
	local last = 0
	for f = 1, recframe do
		local fr = recinputstream[f]
		if fr ~= nil then
			for p = 1, nplayers do if fr[p] ~= nil and fr[p] ~= "" then last = f end end
		end
	end
	if last == 0 then
		recframe = 0
		recinputstream = {}
		return false, "empty"
	end
	if q.trim then
		local first = q.first or 1
		local t = {}
		for f = first, last do t[f - first + 1] = recinputstream[f] end
		recinputstream = t
		recframe = last - first + 1
		if q.pos ~= nil then rec_pos_at_start = q.pos end
		if q.facing ~= nil then rec_facing_at_start = q.facing end
	end
	local n = recframe
	finalize(recinputstream, quick_file())
	return true, n
end

-- Ends the take and writes nothing (the setting turned off, the character
