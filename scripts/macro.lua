			recframe = recframe+1
			for p = 1,nplayers do
				for n,key in ipairs(keymap or {}) do
					if joypad.get(p)[keymap[n][p]] == 1 or joypad.get(p)[keymap[n][p]] == true then
						recinputstream[recframe] = recinputstream[recframe] or {}
						recinputstream[recframe][p] = not recinputstream[recframe][p] and key.symbol or recinputstream[recframe][p] .. key.symbol
					end
				end
			end
			if quick_rec ~= nil then quick_frame() end
		end

		if message_hold > 0 then message_hold = message_hold - 1 end
		if (playing or recording) and message_hold == 0 then
			local pmesg = playing and ("macro playing: " .. frame .. "/" .. macrosize) or ""
			if wait.duration then
				pmesg = pmesg .. "; incremental wait: " .. wait.duration .. wait.change
			elseif loopmode then
				pmesg = pmesg .. " in loop mode"
			end
			local rmesg = recording and "macro recording: " .. recframe or ""
			emu.message(pmesg .. (playing and recording and "   " or "") .. rmesg)
		end
	end,

	["registerExit"] = function() --Attempt to save if the script exits while recording
		if recording then recording = false finalize(recinputstream) end
	end,

	["registerBefore"] = function()
		if not input.registerhotkey and not guiregisterhax then --as a last resort, check for hotkeys the hard way (snes9x & vba)
			local nowplaykey = input.get()[playkey]
			if nowplaykey and not oldplaykey then
				playcontrol()
			end
			oldplaykey = nowplaykey
	
			local nowrecordkey = input.get()[recordkey]
			if nowrecordkey and not oldrecordkey then
				reccontrol()
			end
			oldrecordkey = nowrecordkey
	
			local nowpausekey = input.get()[togglepausekey]
			if nowpausekey and not oldpausekey then
				togglepause()
			end
			oldpausekey = nowpausekey
	
			local nowloopkey = input.get()[toggleloopkey]
			if nowloopkey and not oldloopkey then
				toggleloop()
			end
			oldloopkey = nowloopkey
		end
			
		update_loop_menu_hold()

		-- LOOPED PLAYBACK WAITS FOR THE DUMMY TO BE ABLE TO ACT.
		--
		-- A loop used to restart on the frame after the macro ended, with no
		-- regard for what the dummy was doing. Since the trailing neutral is
		-- trimmed off a recording, the next pass began while the character was
		-- still in recovery, and anything that is not a special-move command
		-- has to land on free+0 or it simply does not come out.
		--
		-- $05 (0xFF8805) is non-zero through hit/block stun and knockdown -
		-- the same byte debugKnockdown starts recording on and calls "hurt".
		-- $06 (0xFF8806) is the action id: guardCancel reads 0x14 as a dash
		-- and 0x04 as the actionable wake-up sub-state, and dummyState treats
		-- 0x00 as the stance a guard can come out of. Both clear means
		-- standing neutral, which is exactly when a fresh pass can start.
		--
		-- Not used when a savestate is in play: loading it puts the character
		-- back where it was captured, which already does this job.
		if loop_pending and globals.hotkeys_armed ~= true then
			-- Left the match (character select, Lua key 4). $05/$06 mean
			-- nothing here, so a pending restart is dropped rather than left
			-- hanging over into the next match.
			loop_pending = false
		elseif loop_pending and not loop_menu_hold_active() and not game_frozen()
		       and (loop_phase == "before" or p2_can_act()) then
			-- AFTER is counted once the previous pass has recovered. When it
			-- ends, restore the recorded spacing (or savestate), then count
			-- BEFORE at that restored setup before the next pass goes out.
			-- BEFORE holds the playback, not the characters: nothing is frozen
			-- during it, so a dummy with an action set will still take it.
			if loop_gap > 0 then
				loop_gap = loop_gap - 1
			elseif loop_phase == "before" then
				-- A restore still on its way owns both characters, and starting
				-- the pass into that would play the take at the wrong spacing.
				-- Held rather than returned out of: the rest of this function
				-- still has a frame of macro playback to look after.
				local _pm = positionModule
				local _busy = _pm ~= nil and _pm.camera_restore_busy ~= nil
				              and _pm.camera_restore_busy()
				if not _busy then
					loop_pending = false
					playcontrol(true)
				end
			else
				-- A loop loads no state (v11.7.28): Use Savestate Upon Recording is
				-- gone, and a state is saved and restored by hand
				-- (trainingState.lua). Loading one here could also end a take: a
				-- state from before it has no recinputstream, and registerLoad's
				-- bulletproof() then switched recording off mid-take - the wizard
				-- recording "stopping by itself" with the setting on.
				if globals.options.restore_recorded_position == true then
					-- Put the two back at the distance the take was recorded
					-- from, so a loop keeps meeting the dummy at the same
					-- spacing instead of drifting apart over the passes. Files
					-- written before the header carried it report nothing and
					-- are left alone.
					restore_playback_pos()
				end
				loop_phase = "before"
				loop_gap = globals.options.loop_interval_before_frames or 0
				if loop_gap <= 0 then
					loop_pending = false
					playcontrol(true)
				end
			end
		end

		-- THE RANDOM START WAIT RUNNING OUT. Before the playback block below, so
		-- the first frame goes out on this same callback - exactly where a start
		-- with no wait would have put it.
		if start_wait ~= nil and globals.hotkeys_armed ~= true then
			-- Left the match: same as a pending loop restart, dropped.
			start_wait = nil
			inputstream = nil
		elseif start_wait ~= nil
		       and start_wait_tick(start_wait, memory.readbyte(0xFF8081)) then
			start_wait = nil
			dostate(frame)
			playing = true
			playback_serial = playback_serial + 1
			framediff = emu.framecount()
		end

		--framediff check is necessary for emus where registerbefore runs multiple times per frame
		if playing and (loop_menu_hold_active() or game_frozen()) then
			-- HOLD IT WHERE IT IS, DO NOT BANK THE FRAMES.
			--
			-- Skipping the advance alone leaves emu.framecount() running while
			-- the macro frame stands still, and the check above then reads as
			-- satisfied several times over. On an emulator that calls
			-- registerBefore more than once per displayed frame the macro
			-- would spend the frames after the hold racing to catch up, which
			-- is the opposite of resuming from the same recorded position.
			-- Re-seeding framediff keeps frame == framecount - framediff true
			-- throughout, so the hold costs the macro nothing but time.
			framediff = emu.framecount() - frame
		elseif playing and emu.framecount()-frame >= framediff then
			frame = frame+1
			dostate(frame)
			inputstream[frame] = inputstream[frame] or {}
			for p = 1,nplayers do
				inputstream[frame][p] = inputstream[frame][p] or {}
			end
			if fba or mame then --In fba and mame, joypad.set is called once without a player number.
				keytable = {}
				for p = 1,nplayers do
					for n,key in ipairs(keymap) do
						if inputstream[frame][p][key.symbol] then
							keytable[keymap[n][p]] = true
						end
					end
					for n,control in ipairs(analog) do
						if inputstream[frame][p][control.symbol] then
							keytable[analog[n][p]] = inputstream[frame][p][control.symbol]
						end
					end
				end
				if keytable["Reset"] == 1 and emu.softreset then emu.softreset() end
			else --In other emus, joypad.set is called separately for each player.
				keytable = {}
				for p = 1,nplayers do
					keytable[p] = joypad.getdown(p) --This allows lua+user input
					for n,key in ipairs(keymap) do
						if inputstream[frame][p][key.symbol] then keytable[p][keymap[n][p]] = true end
					end
				end
			end
			if globals.options.looped_playback == false then
				if frame > macrosize then
					playing = false
					inputstream = nil
					pausenow = pauseafterplay
					if wait.duration then
						wait.duration = wait.duration + wait.increment
						if wait.duration < 0 then wait.duration = 0 end
						playcontrol(true)
					elseif loopmode then
						loop_pending = true
						loop_phase = "after"
						loop_gap = globals.options.loop_interval_after_frames or 0
						loop_reload = false
					else
						print("Macro finished playing.") print()
					end
				end
			end
			if globals.options.looped_playback == true then
				if frame > macrosize then
					playing = false
					inputstream = nil
					pausenow = pauseafterplay
					loop_pending = true
					loop_phase = "after"
					loop_gap = globals.options.loop_interval_after_frames or 0
					loop_reload = false
				end
			end
		end
	
			--must joypad.set the keytable with every registerbefore, even if multiple times per frame, to ensure all keys are sent
			if playing then
				if fba or mame then
					-- joypad.set(keytable)
				else
					for p = 1,nplayers do joypad.set(p, keytable[p]) end
				end
			end

			globals.playing = playing
			globals.recording = recording
			return {
				-- From outside (guardCancel.lua's Recording counters, tests): not
				-- the player's own start. user_play is that one.
				["playcontrol"] = function(silent) user_owned = false ; playcontrol(silent) end,
				["reccontrol"] = reccontrol,  
				["toggleloop"] = toggleloop,
				["setloop"] = setloop,
				["stop_macro_playback"] = stop_macro_playback,
				["start_macro_playback"] = start_macro_playback,
				["recording"] = recording,
				["playing"] = playing,
				["playback_serial"] = playback_serial,
				-- Waiting out a Random Start Wait. Nothing is playing yet, so
				-- the dummy's own settings still drive it; asking for playback
				-- again in this state would call it off (playcontrol toggles).
				["starting"] = (start_wait ~= nil),
				["get_keytable"] = function()
					-- Freeze an already-running loop as well as a pending restart.
					-- Returning no macro keys prevents the last recorded input from
					-- leaking through during the 30-frame post-menu hold.
					if loop_menu_hold_active() then return {} end
					-- if playing then return keytable else return {} end
					if keytable then
						-- if player_objects[2].flip_input then
						-- 	local should_flip = player_objects[2].flip_input
						-- 	local flipped = {}
						-- 	for k,v in pairs(keytable) do
						-- 		if k == "P2 Right" then
						-- 			flipped["P2 Left"] = true
						-- 		elseif k == "P2 Left" then
						-- 			flipped["P2 Right"] = true
						-- 		else
						-- 			flipped[k] = v
						-- 		end
						-- 	end
						-- 	keytable = flipped
						-- end
						return keytable
					else
						return {}
					end
				end,
				["begin_quick_recording"] = begin_quick_recording,
				["finish_quick_recording"] = finish_quick_recording,
				["cancel_quick_recording"] = cancel_quick_recording,
				["quick_recording_active"] = quick_recording_active,
				["quick_file"] = quick_file,
				["quick_file_exists"] = quick_file_exists,
				["play_quick"] = play_quick,
				["quick_playing"] = quick_playing,
				["stop_all_playback"] = stop_all_playback,
				["copy_quick_to_slot"] = copy_quick_to_slot,
				["user_play"] = user_play,
