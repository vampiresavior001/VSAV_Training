-- Plays the quick take, through the same start as Volume Down: Looped
-- Playback, the Random Start Wait, Reset Distance Each Loop apply as they do
-- to a slot. Whatever plays is stopped first.
function play_quick()
	if recording then return false end
	if playing or start_wait ~= nil or loop_pending then stop_macro_playback() end
	inputstream = nil
	if not quick_file_exists() then return false end
	slot_override = quick_file()
	playcontrol()
	if playing or start_wait ~= nil then last_user_play, user_owned = "quick", true end
	return playing or start_wait ~= nil
end

-- PLAY AFTER RESTORE (trainingState.lua, Recording tab; user, 2026-10-21, from a
-- player's request: restoring a state and then pressing play was two steps).
-- What the player started last - the quick take or the Playback Slot - is kept
-- here, so a restore can start it again from its first frame. Only the
-- player's own starts count: Volume Down, Play Recording, Play Quick Recording
-- and the take Coin plays. A Reversal / Counter Attack - Recording start
-- (guardCancel.lua) is the dummy's and is not one. A character select forgets
-- it (trainingState.new_session).
function user_play()
	playcontrol()
	if playing or start_wait ~= nil then
		last_user_play = (slot_override ~= nil) and "quick" or "slot"
		user_owned = true
	end
end

-- Starts what was played last from its start (whatever plays is stopped
-- first). true: started, or waiting out its Random Start Wait.
function replay_last()
	if recording or last_user_play == nil then return false end
	if last_user_play == "quick" then return play_quick() end
	stop_macro_playback()
	inputstream = nil
	playcontrol()
	if playing or start_wait ~= nil then user_owned = true end
	return playing or start_wait ~= nil
end

function forget_user_play() last_user_play = nil end

-- THE PLAYER'S OWN PLAYBACK OWNS P2 (user, 2026-10-22: Action Steps came out in
-- the middle of a playback, mixed into it; "止める" for the gaps between loops
-- too). True from a start of the player's own - user_play, play_quick,
-- replay_last - until it stops: playing, waiting out its Random Start Wait, or
-- between loops. dummyState.lua answers Guard Action 'none' through it, so
-- nothing of the dummy's own counter arms or runs; the guard itself stays.
-- A start from anywhere else (Reversal / Counter Attack - Recording, through
-- the table's playcontrol below) is the dummy's and is not one.
function user_playback()
	return user_owned and (playing or start_wait ~= nil or loop_pending)
end

-- The quick take is what plays (or waits to start, or waits between loops).
function quick_playing()
	return slot_override ~= nil and (playing or start_wait ~= nil or loop_pending)
end

-- Everything that plays stops, the pass between loops included.
function stop_all_playback()
	stop_macro_playback()
	inputstream = nil
end

-- Copies the quick take into a numbered slot for this dummy (1 to 5, picked on
-- the menu row; none: the menu's Playback Slot) - the only way it reaches one.
function copy_quick_to_slot(n)
	local src = io.open(path:gsub("\\", "/") .. quick_file(), "r")
	if src == nil then return false, "no quick recording" end
	local text = src:read("*a")
	src:close()
	local dir = ""
	if globals.options.use_character_specific_slots then dir = globals.dummy.p2_char end
	local slot = (type(n) == "number" and n >= 1 and n <= 5) and ("slot_" .. n .. ".mis") or globals.dummy.recording_slot
	local name = dir .. "/" .. slot
	local dst = io.open(path:gsub("\\", "/") .. name, "w")
	if dst == nil then return false, "cannot write " .. name end
	dst:write(text)
	dst:close()
	return true, name
end

-- Play the temp recording once, for the wizard's confirmation pass. The
-- user's own loop setting must not apply here: a looped preview would never
-- end and the wizard would wait on it for good. The setting is put back by
-- end_temporary_playback.
local wizard_saved_loop = nil

function play_temporary_recording()
	if playing or recording or start_wait ~= nil then return false end
	-- parse() returns frame (0) on success and nil on failure; 0 is truthy.
	if not parse(WIZARD_TEMP_NAME) then return false end
	if macrosize == nil or macrosize == 0 then return false end
	wizard_saved_loop = globals.options.looped_playback
	globals.options.looped_playback = false
	loopmode = false
	dostate(frame)
	playing = true
	framediff = emu.framecount()
	return true
end

function end_temporary_playback()
	playing = false
	inputstream = nil
	if wizard_saved_loop ~= nil then
		globals.options.looped_playback = wizard_saved_loop
		wizard_saved_loop = nil
	end
end

function get_recording_status()
	return { recording = recording, playing = playing, frames = recframe, temp_name = WIZARD_TEMP_NAME,
	         starting = (start_wait ~= nil), loop_pending = loop_pending }
end

